#!/bin/sh
#
# Lab4 autograder.
#
# Usage: tools/grade.sh [-v]
#   -v  verbose: show the build and QEMU output on the terminal, and stop at the first failed check.
#
# Flow: build the kernel, run QEMU once until the kernel reaches readline() (kernel monitor), then
# check the serial log saved in $qemu_out against a list of expected lines. Each check is worth
# 10 points (pts=10); a check passes only if every expected line is found. The final score is the
# sum over checks, and the script exits with status 1 if it is not full marks.
# The checks run the tests injected by tools/inject.py (test_lab4.c), so they test the student's
# pmm_init, proc_init and init_main through their observable output.

verbose=false
if [ "x$1" = "x-v" ]; then
    verbose=true
    out=/dev/stdout
    err=/dev/stderr
else
    out=/dev/null
    err=/dev/null
fi

## make & makeopts
# prefer GNU make (gmake) when it is installed, otherwise use make
if gmake --version > /dev/null 2>&1; then
    make=gmake;
else
    make=make;
fi

# --quiet suppresses command echo, -j runs the build in parallel
makeopts="--quiet --no-print-directory -j"

# make_print <name>: print the value of Makefile variable <name> via the print-<name> target
make_print() {
    echo `$make $makeopts print-$1`
}

# build everything (the default make target) before grading
echo `$make`

## command tools
awk='awk'
bc='bc'
date='date'
grep='grep'
rm='rm -f'
sed='sed'

## symbol table
# kernel symbol table generated by the build; maps function names to addresses
sym_table='obj/kernel.sym'

## gdb & gdbopts
# gdb is used to set a breakpoint on $brkfun and stop QEMU there
gdb="$(make_print GDB)"
gdbport='1234'

gdb_in="$(make_print GRADE_GDB_IN)"

## qemu & qemuopts
# qemu binary path from the Makefile; the serial output of the kernel goes to $qemu_out
qemu="$(make_print qemu)"

qemu_out="$(make_print GRADE_QEMU_OUT)"

# use the modern "-gdb" option when QEMU supports it, else the older "-s -p" form
if $qemu -nographic -help | grep -q '^-gdb'; then
    qemugdb="-gdb tcp::$gdbport"
else
    qemugdb="-s -p $gdbport"
fi

## default variables
# default_timeout: seconds before QEMU is killed (30 s)
default_timeout=30
# default_pts: default points per check (overridden per check, lab4 uses 10)
default_pts=5

# pts:       points awarded for each check in the current group
# part:      points earned so far in the current group (reset by show_part/update_score)
# part_pos:  maximum points for the current group
# total, total_pos: running score and maximum over all groups
pts=5
part=0
part_pos=0
total=0
total_pos=0

## default functions
# update_score: add the current group's points to the totals and reset the group counters
update_score() {
    total=`expr $total + $part`
    total_pos=`expr $total_pos + $part_pos`
    part=0
    part_pos=0
}

# get_time: print the current time in seconds with nanosecond fraction (used for timing)
get_time() {
    echo `$date +%s.%N 2> /dev/null`
}

# show_part <name>: print the score of one group, then fold it into the totals
show_part() {
    echo "Part $1 Score: $part/$part_pos"
    echo
    update_score
}

# show_final: print the total score; exits with status 1 if any points were lost
show_final() {
    update_score
    echo "Total Score: $total/$total_pos"
    if [ $total -lt $total_pos ]; then
        exit 1
    fi
}

# show_time: print the elapsed time since t0 (set by run_qemu) in parentheses
show_time() {
    t1=$(get_time)
    time=`echo "scale=1; ($t1-$t0)/1" | $sed 's/.N/.0/g' | $bc 2> /dev/null`
    echo "(${time}s)"
}

# show_build_tag <tag>: print a left-aligned build-step label without a newline
show_build_tag() {
    echo "$1:" | $awk '{printf "%-24s ", $0}'
}

# show_check_tag <tag>: print an indented check label padded to a fixed column
show_check_tag() {
    echo "$1:" | $awk '{printf "  -%-40s  ", $0}'
}

# show_msg <status> [lines...]: print a status word and, if given, indented detail lines
show_msg() {
    echo $1
    shift
    if [ $# -gt 0 ]; then
        echo -e "$@" | awk '{printf "   %s\n", $0}'
        echo
    fi
}

# pass [msg...]: mark the current check OK and award $pts points
pass() {
    show_msg OK "$@"
    part=`expr $part + $pts`
    part_pos=`expr $part_pos + $pts`
}

# fail [msg...]: mark the current check WRONG; the $pts points are not awarded
fail() {
    show_msg WRONG "$@"
    part_pos=`expr $part_pos + $pts`
}

# run_qemu: start QEMU in the background with serial output to $qemu_out, optionally with a
# breakpoint. Uses $brkfun, $timeout, $qemuopts; sets $t0 for show_time.
run_qemu() {
    # Run qemu with serial output redirected to $qemu_out. If $brkfun is non-empty,
    # wait until $brkfun is reached or $timeout expires, then kill QEMU
    qemuextra=
    if [ "$brkfun" ]; then
        qemuextra="-S $qemugdb"
    fi

    if [ -z "$timeout" ] || [ $timeout -le 0 ]; then
        timeout=$default_timeout;
    fi

    t0=$(get_time)
    (
        ulimit -t $timeout
        exec $qemu -nographic $qemuopts -serial file:$qemu_out -monitor null -no-reboot $qemuextra
    ) > $out 2> $err &
    pid=$!

    # wait for QEMU to start
    sleep 1

    if [ -n "$brkfun" ]; then
        # find the address of the kernel $brkfun function
        brkaddr=`$grep " $brkfun\$" $sym_table | $sed -e's/ .*$//g'`
        brkaddr_phys=`echo $brkaddr | sed "s/^c0/00/g"`
        (
            echo "target remote localhost:$gdbport"
            echo "break *0x$brkaddr"
            if [ "$brkaddr" != "$brkaddr_phys" ]; then
                echo "break *0x$brkaddr_phys"
            fi
            echo "continue"
        ) > $gdb_in

        $gdb -batch -nx -x $gdb_in > /dev/null 2>&1

        # make sure that QEMU is dead
        # on OS X, exiting gdb doesn't always exit qemu
        kill $pid > /dev/null 2>&1
    fi
}

# build_run <tag> [defs]: rebuild with -DDEBUG_GRADE, run QEMU, and keep a copy of its log as .<tag>.log
build_run() {
    # usage: build_run <tag> <args>
    show_build_tag "$1"
    shift

    if $verbose; then
        echo "$make $@ ..."
    fi
    $make $makeopts $@ 'DEFS+=-DDEBUG_GRADE' > $out 2> $err

    if [ $? -ne 0 ]; then
        echo $make $@ failed
        exit 1
    fi

    # now run qemu and save the output
    run_qemu

    show_time

    cp $qemu_out .`echo $tag | tr '[:upper:]' '[:lower:]' | sed 's/ /_/g'`.log
}

# check_result <label> <check> [args...]: wait for QEMU output, then run <check> on it
check_result() {
    # usage: check_result <tag> <check> <check args...>
    show_check_tag "$1"
    shift

    # give qemu some time to run (for asynchronous mode)
    if [ ! -s $qemu_out ]; then
        sleep 4
    fi

    if [ ! -s $qemu_out ]; then
        fail > /dev/null
        echo 'no $qemu_out'
    else
        check=$1
        shift
        $check "$@"
    fi
}

# check_regexps [!] <line> [-] [!] <line> ...: pass if every expected line occurs in $qemu_out.
# A leading "!" requires that the next line must NOT occur; a leading "-" makes the next
# pattern an extended regular expression (grep -E) instead of a fixed string (grep -F).
check_regexps() {
    okay=yes
    not=0
    reg=0
    error=
    for i do
        if [ "x$i" = "x!" ]; then
            not=1
        elif [ "x$i" = "x-" ]; then
            reg=1
        else
            if [ $reg -ne 0 ]; then
                $grep '-E' "^$i\$" $qemu_out > /dev/null
            else
                $grep '-F' "$i" $qemu_out > /dev/null
            fi
            found=$(($? == 0))
            if [ $found -eq $not ]; then
                if [ $found -eq 0 ]; then
                    msg="!! error: missing '$i'"
                else
                    msg="!! error: got unexpected line '$i'"
                fi
                okay=no
                if [ -z "$error" ]; then
                    error="$msg"
                else
                    error="$error\n$msg"
                fi
            fi
            not=0
            reg=0
        fi
    done
    if [ "$okay" = "yes" ]; then
        pass
    else
        fail "$error"
        if $verbose; then
            exit 1
        fi
    fi
}

# run_test [-tag <tag>] [-Ddef...] [-check <check>] checkargs ...: build with the given defines,
# run QEMU and run a check (default check_regexps) on its output. Used for template-style tests.
run_test() {
    # usage: run_test [-tag <tag>] [-Ddef...] [-check <check>] checkargs ...
    tag=
    check=check_regexps
    while true; do
        select=
        case $1 in
            -tag)
                select=`expr substr $1 2 ${#1}`
                eval $select='$2'
                ;;
        esac
        if [ -z "$select" ]; then
            break
        fi
        shift
        shift
    done
    defs=
    while expr "x$1" : "x-D.*" > /dev/null; do
        defs="DEFS+='$1' $defs"
        shift
    done
    if [ "x$1" = "x-check" ]; then
        check=$2
        shift
        shift
    fi

    $make $makeopts touch > /dev/null 2>&1
    build_run "$tag" "$defs"

    check_result 'check result' "$check" "$@"
}

# quick_run <tag> [-Ddef...]: build and run QEMU without checking the output
quick_run() {
    # usage: quick_run <tag> [-Ddef...]
    tag="$1"
    shift
    defs=
    while expr "x$1" : "x-D.*" > /dev/null; do
        defs="DEFS+='$1' $defs"
        shift
    done

    $make $makeopts touch > /dev/null 2>&1
    build_run "$tag" "$defs"
}

# quick_check <tag> <line>...: check the existing QEMU output for the expected lines (no rebuild)
quick_check() {
    # usage: quick_check <tag> checkargs ...
    tag="$1"
    shift
    check_result "$tag" check_regexps "$@"
}

## kernel image
# path of the kernel image the grader runs (bin/ucore.img)
osimg=$(make_print ucoreimg)

## swap image
swapimg=$(make_print swapimg)

## set default qemu-options
# RISC-V "virt" machine, OpenSBI firmware (-bios default), kernel loaded from bin/ucore.img
qemuopts="-machine virt -nographic -bios default -kernel bin/ucore.img"

## set break-function, default is readline
# QEMU is stopped when the kernel reaches readline() (the kernel monitor prompt), so the log
# holds everything printed before the monitor starts
brkfun=readline

run_qemu

## check now!!

# quick_run 'Check VMM'

# 10 points: pmm_init runs test_lab4_pmm_basic (injected at the end of pmm_init)
pts=10
quick_check 'check PMM'                                     \
    '[Test PMM] PASS'

# 10 points: proc_init runs test_lab4_process_create (injected at the end of proc_init)
pts=10
quick_check 'check Process Create'                          \
    '[Test Process Create] PASS'

# 10 points: init_main runs test_lab4_schedule (injected at the start of init_main), and the
# user-mode test program must print its normal output too
pts=10
quick_check 'check Schedule'                                \
    '[Test Schedule] PASS'                                   \
    'this initproc, pid = 1, name = "init"'                 \
    'To U: "Hello world!!".'                                \
    'To U: "en.., Bye, Bye. :)"'

## print final-score
show_final
